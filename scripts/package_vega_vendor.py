#!/usr/bin/env python3
"""FIG-02B: package the pinned Vega, Vega-Lite and vega-interpreter builds into assets/lib (reproducible).

    python3 scripts/package_vega_vendor.py <dir with the three npm tarballs>

Fetch the tarballs with `npm pack vega@6.4.0 vega-lite@6.5.0 vega-interpreter@2.3.2`. Each tarball must match
the registry integrity pinned below. vega.min.js and vega-lite.min.js are copied unchanged. vega-interpreter is
published only as an ES module importing vega-util; it is rewritten mechanically into a classic script that takes
the same three functions from the already-loaded `vega` global (no bundler, no other change), so Graph Studio can
evaluate Vega expressions without eval / new Function. Re-running produces byte-identical output.
"""
import base64
import hashlib
import io
import json
import pathlib
import re
import sys
import tarfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
PINS = {
    "vega": ("6.4.0", "sha512-rHXCq2LpEWCLMjXBEj7hocY9G0/i5TGYRayGGSj06VTF4+l2IG2Z7oeZKCjWbUh/7hTE/mVhbaOPB72wCElh6g=="),
    "vega-lite": ("6.5.0", "sha512-fMXF6s0MrIg0UTWnLIfeFtgSLzVhyzSKobzGrh5rhS+mL6FOYFG3m7ouJ4U23gj65EK+gl9FIIT5w7wLNaAzkA=="),
    "vega-interpreter": ("2.3.2", "sha512-JDAoi3taFcCDLujZG84TNNUXdkAZ5WsSHssx8lWVYaxb9Slsjk7v7PtRIYXpSlUwLaKGRBqoJ9KDs36Z0eMEIw=="),
}
FILES = {"vega": "build/vega.min.js", "vega-lite": "build/vega-lite.min.js", "vega-interpreter": "build/vega-interpreter.js"}
INTERPRETER_IMPORT = "import { ascending, isString, DisallowedObjectProperties } from 'vega-util';\n"
INTERPRETER_EXPORT = "export { expression as expressionInterpreter };\n"


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def member(tar, name):
    return tar.extractfile(tar.getmember("package/" + name)).read()


def classic_interpreter(src):
    text = src.decode("utf-8")
    if text.count(INTERPRETER_IMPORT) != 1 or text.count(INTERPRETER_EXPORT) != 1 or re.search(r"^(import|export)\b", text.replace(INTERPRETER_IMPORT, "").replace(INTERPRETER_EXPORT, ""), re.M):
        raise SystemExit("vega-interpreter build changed shape; review before packaging")
    body = text.replace(INTERPRETER_IMPORT, "").replace(INTERPRETER_EXPORT, "")
    return ("/*! vega-interpreter 2.3.2 (BSD-3-Clause) as a classic script for Sustainable Catalyst Lab FIG-02B.\n"
            " * Generated by scripts/package_vega_vendor.py from build/vega-interpreter.js: the vega-util import is taken\n"
            " * from the loaded vega global and the export is assigned to window.vegaInterpreter. Nothing else differs. */\n"
            "(function (root) {\n'use strict';\n"
            "if (!root.vega) { throw new Error('vega-interpreter needs vega loaded first'); }\n"
            "var ascending = root.vega.ascending, isString = root.vega.isString, DisallowedObjectProperties = root.vega.DisallowedObjectProperties;\n"
            + body +
            "root.vegaInterpreter = Object.freeze({ expressionInterpreter: expression, version: '2.3.2' });\n"
            "}(typeof self !== 'undefined' ? self : this));\n").encode("utf-8")


def main():
    src_dir = pathlib.Path(sys.argv[1])
    for name, (version, integrity) in PINS.items():
        tgz = (src_dir / f"{name}-{version}.tgz").read_bytes()
        got = "sha512-" + base64.b64encode(hashlib.sha512(tgz).digest()).decode()
        if got != integrity:
            raise SystemExit(f"{name}-{version}.tgz does not match the registry integrity")
        with tarfile.open(fileobj=io.BytesIO(tgz)) as tar:
            original = member(tar, FILES[name])
            licence = member(tar, "LICENSE")
            pkg = json.loads(member(tar, "package.json"))
        if pkg["version"] != version or pkg["license"] != "BSD-3-Clause":
            raise SystemExit(f"{name}: unexpected version or licence")
        out_dir = ROOT / "assets" / "lib" / f"{name}-{version}"
        out_dir.mkdir(parents=True, exist_ok=True)
        if name == "vega-interpreter":
            out_name, data = "vega-interpreter.classic.js", classic_interpreter(original)
            origin = f"npm {name}@{version} {FILES[name]} (ES module), rewritten to a classic script by scripts/package_vega_vendor.py"
        else:
            out_name, data = pathlib.Path(FILES[name]).name, original
            origin = f"npm {name}@{version} {FILES[name]} (unchanged)"
        (out_dir / out_name).write_bytes(data)
        (out_dir / "LICENSE").write_bytes(licence)
        (out_dir / "SOURCE.json").write_text(json.dumps({
            "library": name, "version": version, "file": out_name, "sha256": sha256(data), "bytes": len(data),
            "origin": origin, "npmTarballIntegrity": integrity, "npmFileSha256": sha256(original),
            "licence": "BSD-3-Clause (see LICENSE)", "network": "Served from the plugin directory only; no CDN.",
            "reason": "FIG-02B Vega-Lite views in Graph Studio, rendered to SVG with the CSP-safe expression interpreter (no eval).",
        }, indent=2) + "\n")
        print(f"{name} {version} {out_name} sha256={sha256(data)}")


if __name__ == "__main__":
    main()
